namespace ShapeForge
{
    /// <summary>
    /// Defines standard semantic roles for articulated humanoid-compatible models.
    /// </summary>
    public static class ShapeRigRoles
    {
        /// <summary>Identifies the model root.</summary>
        public const string Root          = "humanoid/root";
        /// <summary>Identifies the pelvis or primary body translation joint.</summary>
        public const string Hips          = "humanoid/hips";
        /// <summary>Identifies the primary spine joint.</summary>
        public const string Spine         = "humanoid/spine";
        /// <summary>Identifies the head joint.</summary>
        public const string Head          = "humanoid/head";
        /// <summary>Identifies the left shoulder joint.</summary>
        public const string LeftShoulder  = "humanoid/left-shoulder";
        /// <summary>Identifies the left elbow joint.</summary>
        public const string LeftElbow     = "humanoid/left-elbow";
        /// <summary>Identifies the right shoulder joint.</summary>
        public const string RightShoulder = "humanoid/right-shoulder";
        /// <summary>Identifies the right elbow joint.</summary>
        public const string RightElbow    = "humanoid/right-elbow";
        /// <summary>Identifies the left hip joint.</summary>
        public const string LeftHip       = "humanoid/left-hip";
        /// <summary>Identifies the left knee joint.</summary>
        public const string LeftKnee      = "humanoid/left-knee";
        /// <summary>Identifies the right hip joint.</summary>
        public const string RightHip      = "humanoid/right-hip";
        /// <summary>Identifies the right knee joint.</summary>
        public const string RightKnee     = "humanoid/right-knee";
    }
}
